async function main() {
  console.log('Seeding MASSIVE database...');
  
  // Clear everything (optional, but good for clean state)
  await prisma.characterAnswer.deleteMany({});
  await prisma.character.deleteMany({});
  await prisma.question.deleteMany({});
  
  const questionMap: Record<number, number> = {};
  for (let i = 0; i < questionsList.length; i++) {
    const q = await prisma.question.upsert({
      where: { text: questionsList[i] },
      update: {},
      create: { text: questionsList[i] },
    });
    questionMap[i] = q.id;
  }

  for (const c of chars) {
    const name = c[0] as string;
    const desc = c[1] as string;
    const traits = c.slice(2) as number[];
    
    const character = await prisma.character.upsert({
      where: { name: name },
      update: { description: desc },
      create: { name: name, description: desc, imageUrl: '' },
    });

    for (let i = 0; i < questionsList.length; i++) {
      let weight = 0.0;
      
      if (traits.includes(i)) {
        weight = 1.0;
      } else {
        weight = 0.0;
        
        // Logical mutually exclusive traits
        if (i === 1 && traits.includes(2)) weight = 0.0; // female -> not male
        if (i === 2 && traits.includes(1)) weight = 0.0; // male -> not female
        if (i === 0 && (traits.includes(3) || traits.includes(4) || traits.includes(5) || traits.includes(6))) weight = 0.0; // fictional -> not real
        if ((i === 3 || i === 4 || i === 5 || i === 6) && traits.includes(0)) weight = 0.0; // real -> not fictional
        if (i === 11 && traits.includes(0) === false) weight = 0.0; // dead only applies if real (usually)
      }

      await prisma.characterAnswer.upsert({
        where: { characterId_questionId: { characterId: character.id, questionId: questionMap[i] } },
        update: { weight },
        create: { characterId: character.id, questionId: questionMap[i], weight },
      });
    }
  }

  console.log('Massive seeding finished!');
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
