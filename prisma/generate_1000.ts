async function main() {
  console.log('Generating massive 1000+ db...');
  
  await prisma.characterAnswer.deleteMany({});
  await prisma.character.deleteMany({});
  await prisma.question.deleteMany({});

  const questionMap: Record<string, number> = {};
  for (const qText of Object.values(Q)) {
    const q = await prisma.question.create({ data: { text: qText } });
    questionMap[qText] = q.id;
  }

  let totalChars = 0;

  for (const cat of categories) {
    const names = cat.names.split(',');
    for (const name of names) {
      if (!name.trim()) continue;
      
      const charName = name.trim();
      const character = await prisma.character.create({
        data: { name: charName, description: 'Известная личность / Персонаж' }
      });
      totalChars++;

      for (const qText of Object.values(Q)) {
        let weight = 0.5; // Default unknown
        
        if (cat.traits.includes(qText)) {
          weight = 1.0;
        } else {
          weight = 0.0;
          
          if (qText === Q.FEMALE && cat.traits.includes(Q.MALE)) weight = 0.0;
          if (qText === Q.MALE && cat.traits.includes(Q.FEMALE)) weight = 0.0;
          
          if (qText === Q.DEAD && cat.traits.includes(Q.HISTORICAL)) weight = 1.0;
        }

        await prisma.characterAnswer.create({
          data: { characterId: character.id, questionId: questionMap[qText], weight }
        });
      }
    }
  }

  console.log(`Successfully generated ${totalChars} characters and linked all questions!`);
}

main().catch(console.error).finally(() => prisma.$disconnect());
